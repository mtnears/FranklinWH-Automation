NAMES = dict(COUNTRIES)

# Values older versions stored that are not ISO 3166-1 alpha-2
LEGACY_COUNTRY = {'UK': 'GB', 'OTHER': None, 'USA': 'US', 'UNITED STATES': 'US'}

# Before v4.7.0-beta.2 TELEMETRY_REGION was documented as a US *state* code
# (CA, IL, TX). Several state codes are also country codes (CA = Canada,
# DE = Germany, IN = India...), so a 2-letter state value is ambiguous and
# the review asks the user to pick their country instead of guessing.
US_STATES = {
    'AL', 'AK', 'AZ', 'AR', 'CA', 'CO', 'CT', 'DE', 'FL', 'GA', 'HI', 'ID', 'IL', 'IN',
    'IA', 'KS', 'KY', 'LA', 'ME', 'MD', 'MA', 'MI', 'MN', 'MS', 'MO', 'MT', 'NE', 'NV',
    'NH', 'NJ', 'NM', 'NY', 'NC', 'ND', 'OH', 'OK', 'OR', 'PA', 'RI', 'SC', 'SD', 'TN',
    'TX', 'UT', 'VT', 'VA', 'WA', 'WV', 'WI', 'WY', 'DC'}


def ordered():
    """(code, name) for a dropdown: common markets first, then all by name."""
    common = [(c, NAMES[c]) for c in COMMON]
    return common + [(c, n) for c, n in COUNTRIES if c not in COMMON]


def normalize_country(value):
    """(iso2 or None, note or None). None + note means the value can't be used
    as a country code as-is and the user should pick one."""
    if value in (None, ''):
        return None, None
    v = str(value).strip().upper()
    if v in LEGACY_COUNTRY:
        new = LEGACY_COUNTRY[v]
        return new, (f'"{value}" is stored as {new} (ISO 3166-1)' if new else
                     f'"{value}" is not a country; pick your country')
    if v in US_STATES and v != 'US':
        return None, (f'"{value}" looks like a US state code from older versions. Region is now '
                      f'a country code (ISO 3166-1); pick your country'
                      + (f' ({v} is {NAMES[v]} as a country code)' if v in NAMES else '') + '.')
    if v in NAMES:
        return v, None
    return None, f'"{value}" is not an ISO 3166-1 country code; pick your country.'
